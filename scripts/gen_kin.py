import sys, math, random
sys.path.insert(0, "model")
import cordic_vec_model as vm
import kin_model as km

with open("rtl/kin_params.vh", "w") as f:
    f.write("// Auto-generated by scripts/gen_kin.py - do not edit by hand\n")
    f.write("localparam signed [16:0] PI_K   = 17'sd%d;\n" % vm.PI_FX)
    f.write("localparam signed [16:0] HALF_K = 17'sd%d;\n" % (vm.PI_FX // 2))
    f.write("localparam signed [16:0] L1_K   = 17'sd%d;\n" % int(round(km.L1 * km.PS)))
    f.write("localparam signed [16:0] L2_K   = 17'sd%d;\n" % int(round(km.L2 * km.PS)))

random.seed(5)
lines = []
for _ in range(1500):
    t1 = max(-vm.PI_FX, min(vm.PI_FX, int(round(random.uniform(-math.pi, math.pi) * km.AS))))
    t2 = max(0, min(vm.PI_FX, int(round(random.uniform(0, math.pi) * km.AS))))
    x, y = km.fk_fixed(t1, t2)
    lines.append("%04x%04x%04x%04x" % (t1 & 0xFFFF, t2 & 0xFFFF, x & 0xFFFF, y & 0xFFFF))

with open("tb/fk_vectors.hex", "w") as f:
    f.write("\n".join(lines) + "\n")
with open("tb/fk_count.txt", "w") as f:
    f.write("%d\n" % len(lines))
print("wrote rtl/kin_params.vh and %d FK vectors" % len(lines))
