import sys
sys.path.insert(0, "model")
import pid_model as pm
import traj_model as tm
import fopid_model as fm

LAM, MU, M = 0.6, 0.6, 16

def lut(name, w):
    lines = ["function signed [31:0] %s(input integer idx);" % name, "  case (idx)"]
    for i, v in enumerate(w):
        v = int(v)
        lines.append("    %d: %s = %s32'sd%d;" % (i, name, "-" if v < 0 else "", abs(v)))
    lines += ["    default: %s = 32'sd0;" % name, "  endcase", "endfunction"]
    return lines

wi = fm.gl_weights(-LAM, M)
wd = fm.gl_weights(MU, M)
with open("rtl/fopid_params.vh", "w") as f:
    f.write("// Auto-generated by scripts/gen_fopid.py - do not edit by hand\n")
    f.write("localparam integer WS = %d;\n" % fm.WS)
    f.write("\n".join(lut("wi_lut", wi) + lut("wd_lut", wd)) + "\n")

def seq(ref_seq):
    ctrl, plant, pos = fm.FOPID(LAM, MU, M), pm.Plant(), 0
    rows = []
    for k, r in enumerate(ref_seq):
        u = ctrl.step(r, pos)
        assert -32768 <= r <= 32767 and -32768 <= pos <= 32767, "16-bit overflow"
        rows.append((r, pos, u, 1 if k == 0 else 0))
        pos = plant.step(u)
    return rows

q0, q1 = 0, 12288
n = tm.min_log2n(q1 - q0)
quintic = [tm.traj(q0, q1, k, n) for k in range(1 << n)] + [q1] * 300
rows = seq([8192] * 1500) + seq(quintic) + seq([24000] * 2500)

with open("tb/fopid_vectors.hex", "w") as f:
    f.write("\n".join("%04x%04x%04x%04x" % (r & 0xFFFF, p & 0xFFFF, u & 0xFFFF, c)
                      for r, p, u, c in rows) + "\n")
with open("tb/fopid_count.txt", "w") as f:
    f.write("%d\n" % len(rows))

r = fm.evaluate(lambda: fm.FOPID(LAM, MU, M))
print("wrote rtl/fopid_params.vh and %d FO-PID vectors (lambda=%.1f mu=%.1f M=%d)" % (len(rows), LAM, MU, M))
print("Model at M=%d: overshoot %.2f%%, settling %d ms, sse %d LSB, quintic max %d rms %.1f"
      % (M, r["os"], r["ts"], r["sse"], r["mx"], r["rms"]))
