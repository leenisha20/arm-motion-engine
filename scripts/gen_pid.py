import sys
sys.path.insert(0, "model")
import pid_model as pm
import traj_model as tm

with open("rtl/pid_params.vh", "w") as f:
    f.write("// Auto-generated by scripts/gen_pid.py - do not edit by hand\n")
    f.write("localparam signed [63:0] KP_K   = 64'sd%d;\n" % pm.KP)
    f.write("localparam signed [63:0] KI_K   = 64'sd%d;\n" % pm.KI)
    f.write("localparam signed [63:0] KD_K   = 64'sd%d;\n" % pm.KD)
    f.write("localparam signed [31:0] IMAX_K = 32'sd%d;\n" % pm.I_MAX)
    f.write("localparam signed [31:0] UMAX_K = 32'sd%d;\n" % pm.U_MAX)

def seq(ref_seq):
    ctrl, plant, pos = pm.PID(), pm.Plant(), 0
    rows = []
    for k, r in enumerate(ref_seq):
        u = ctrl.step(r, pos)
        assert -32768 <= r <= 32767 and -32768 <= pos <= 32767, "16-bit overflow"
        rows.append((r, pos, u, 1 if k == 0 else 0))
        pos = plant.step(u)
    return rows

q0, q1 = 0, 12288
n = tm.min_log2n(q1 - q0)
quintic = [tm.traj(q0, q1, k, n) for k in range(1 << n)] + [q1] * 300

rows = seq([8192] * 1500) + seq(quintic) + seq([24000] * 2500)
with open("tb/pid_vectors.hex", "w") as f:
    f.write("\n".join("%04x%04x%04x%04x" % (r & 0xFFFF, p & 0xFFFF, u & 0xFFFF, c)
                      for r, p, u, c in rows) + "\n")
with open("tb/pid_count.txt", "w") as f:
    f.write("%d\n" % len(rows))
print("wrote rtl/pid_params.vh and %d PID vectors" % len(rows))
