"""Hardware-matched 2-link IK model (bit-accurate with the RTL to be written in Step 13).

Integer math only, floor shifts like Verilog '>>>':
  num = x^2 + y^2 - (L1^2 + L2^2)              Q4.28
  c2  = round(num * INV / 2^S), clamped        Q2.14  (reciprocal multiply instead of divide)
  s2  = isqrt(2^28 - c2^2)                     Q2.14
  t2  = atan2(s2, c2)                          Q3.13  (CORDIC vectoring)
  k1  = L1 + L2*c2 ;  k2 = L2*s2               Q2.14
  t1  = atan2(y, x) - atan2(k2, k1), wrapped to +-pi
"""
import math, os, random, sys
sys.path.insert(0, "model")
import cordic_vec_model as vm
import kin_model as km

PS, AS = km.PS, km.AS
L1_K = int(round(km.L1 * PS))
L2_K = int(round(km.L2 * PS))
D28 = 2 * L1_K * L2_K
C28 = L1_K * L1_K + L2_K * L2_K
S = 32
INV = int(round((1 << (S + 14)) / D28))
C2_MAX = PS - 1
PI = vm.PI_FX


def ik_hw(x, y):
    num = x * x + y * y - C28
    c2 = (num * INV + (1 << (S - 1))) >> S
    c2 = max(-C2_MAX, min(C2_MAX, c2))
    s2 = math.isqrt((1 << 28) - c2 * c2)
    k1 = L1_K + ((L2_K * c2) >> 14)
    k2 = (L2_K * s2) >> 14
    t2, _ = vm.cordic_atan2(s2, c2)
    aphi, _ = vm.cordic_atan2(k2, k1)
    atgt, _ = vm.cordic_atan2(y, x)
    t1 = atgt - aphi
    if t1 < -PI:
        t1 += 2 * PI
    elif t1 > PI:
        t1 -= 2 * PI
    return t1, t2


def main():
    random.seed(11)
    rmin = abs(km.L1 - km.L2) + 0.03
    rmax = km.L1 + km.L2 - 0.03
    pts = []
    for _ in range(2000):
        r = random.uniform(rmin, rmax)
        a = random.uniform(-math.pi, math.pi)
        pts.append((int(round(r * math.cos(a) * PS)), int(round(r * math.sin(a) * PS))))

    e_ik, e_rt, e_old, lines = [], [], [], []
    for x, y in pts:
        t1, t2 = ik_hw(x, y)
        t1f, t2f = km.ik_float(x / PS, y / PS)
        d1 = abs(t1 / AS - t1f) % (2 * math.pi)
        d1 = min(d1, 2 * math.pi - d1)
        e_ik.append(max(d1, abs(t2 / AS - t2f)))
        xx, yy = km.fk_fixed(t1, t2)
        e_rt.append(math.hypot(xx - x, yy - y) / PS)
        t1o, t2o = km.ik_fixed(x, y)
        xo, yo = km.fk_fixed(t1o, t2o)
        e_old.append(math.hypot(xo - x, yo - y) / PS)
        lines.append("%04x%04x%04x%04x" % (x & 0xFFFF, y & 0xFFFF, t1 & 0xFFFF, t2 & 0xFFFF))

    os.makedirs("tb", exist_ok=True)
    os.makedirs("rtl", exist_ok=True)
    os.makedirs("results", exist_ok=True)
    with open("tb/ik_vectors.hex", "w") as f:
        f.write("\n".join(lines) + "\n")
    with open("tb/ik_count.txt", "w") as f:
        f.write("%d\n" % len(pts))
    with open("rtl/ik_params.vh", "w") as f:
        f.write("// Auto-generated by model/ik_hw_model.py - do not edit by hand\n")
        f.write("localparam signed [31:0] C28_K   = 32'sd%d;\n" % C28)
        f.write("localparam signed [31:0] INV_K   = 32'sd%d;\n" % INV)
        f.write("localparam integer       SH_K    = %d;\n" % S)
        f.write("localparam signed [15:0] C2MAX_K = 16'sd%d;\n" % C2_MAX)

    mm = 1000.0 / 0.55
    with open("results/ik_summary.csv", "w") as f:
        f.write("model,max_roundtrip_err,max_roundtrip_err_mm\n")
        f.write("step9_truncating,%.3e,%.3f\n" % (max(e_old), max(e_old) * mm))
        f.write("hardware_matched,%.3e,%.3f\n" % (max(e_rt), max(e_rt) * mm))

    print("Hardware-matched IK: L1=%.2f L2=%.2f, %d targets, INV=%d, S=%d"
          % (km.L1, km.L2, len(pts), INV, S))
    print("IK angle error vs float   : max %.2e rad" % max(e_ik))
    print("Round-trip, Step 9 model  : max %.2e (%.2f mm)" % (max(e_old), max(e_old) * mm))
    print("Round-trip, HW-matched    : max %.2e (%.2f mm)" % (max(e_rt), max(e_rt) * mm))
    print("PASS" if max(e_rt) < 1e-3 else "FAIL")


if __name__ == "__main__":
    main()
